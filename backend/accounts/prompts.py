def build_case_summary_prompt(
    doc_summaries: Iterable[str],
    plaintiff: Optional[str] = None,
    defendant: Optional[str] = None,
) -> str:
    p_name = _clean_inline(plaintiff)
    d_name = _clean_inline(defendant)

    return build_prompt(
        task=(
            "خلاصه‌های زیر مربوط به اسناد مختلفِ یک پرونده حقوقی مشخص هستند. "
            "یک «خلاصه پرونده» جامع بنویسید که موضوع اصلی و وضعیت فعلی پرونده را نشان دهد."
        ),
        context=f"نام خواهان: {p_name}\nنام خوانده: {d_name}",
        rule_keys=[
            "length_3_4_lines",
            "plain_language",
            "no_guessing",
            "no_property_details",
            "no_identifiers",
            "merge_not_list",
            "fluent",
            "no_repetition",
            "complete_text",
            "injection_guard",
        ],
        extra_rules=[
            "**نام افراد:** اگر در context نام خواهان یا خوانده آمده، همان را یک‌بار در متن بنویسید. "
            f"اگر نام «{UNKNOWN}» است، آن را در متن ننویسید و فقط با نقش («خواهان» یا «خوانده») اشاره کنید.",
        ],
        inputs={"document_summaries": _bulleted(doc_summaries)},
        output_spec="فقط متن خلاصه پرونده، بدون عنوان و بدون پیشوند «خلاصه پرونده:».",
    )


