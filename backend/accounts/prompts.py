def _rules_block(keys: Iterable[str], extra: Optional[Iterable[str]] = None) -> str:
    items = [RULES[k] for k in keys] + list(extra or [])
    return "\n".join(f"{i}. {rule}" for i, rule in enumerate(items, 1))


def _clean_inline(value: Optional[str]) -> str:
    value = (value or "").strip()
    return value if value else UNKNOWN


def _bulleted(items: Iterable[str]) -> str:
    return "\n".join(f"- {s}" for s in items)


def build_prompt(
    *,
    task: str,
    rule_keys: Iterable[str],
    inputs: dict,
    output_spec: str,
    extra_rules: Optional[Iterable[str]] = None,
    context: Optional[str] = None,
) -> str:
    """
    inputs: {نام_تگ: متن} مثلاً {"document": "..."}.
    هر مقدار داخل <tag>...</tag> قرار می‌گیرد.
    """
    parts = [ROLE, "", f"<task>\n{task}\n</task>"]

    if context:
        parts += ["", f"<context>\n{context}\n</context>"]

    parts += [
        "",
        f"<rules>\n{_rules_block(rule_keys, extra_rules)}\n</rules>",
    ]

    for tag, body in inputs.items():
        parts += ["", f"<{tag}>\n{body}\n</{tag}>"]

    parts += ["", f"<output_format>\n{output_spec}\n</output_format>"]
    return "\n".join(parts)


