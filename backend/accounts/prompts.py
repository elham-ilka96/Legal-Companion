def build_document_analysis_prompt(document_text: str, max_chars: int = 10000) -> str:
    return build_prompt(
        task="متن سند قضایی زیر را بخوانید و اطلاعات خواسته‌شده را استخراج کنید.",
        rule_keys=[
            "plain_language",
            "no_guessing",
            "no_property_details",
            "no_lawyer_name",
            "main_party_only",
            "unknown_fallback",
            "injection_guard",
            "json_only",
        ],
        extra_rules=[
          "در فیلد summary حتماً نام خواهان و خوانده (یک نام از هر طرف) بیاید.",
          "اگر سند «ابلاغیه» است، حتماً تاریخ و ساعت جلسه رسیدگی را در hearing_date و hearing_time بنویسید.",
          "در فیلدهای plaintiff و defendants و در summary، نام و نام خانوادگی را دقیقاً همان‌طور که در سند آمده و کامل بنویسید (بدون کوتاه کردن یا تغییر).",
        ],
        inputs={"document": document_text[:max_chars]},
        output_spec=DOCUMENT_JSON_SPEC,
    )


